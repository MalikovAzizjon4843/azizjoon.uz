// Generates public/sitemap.xml from src/data/projects.js and sanity-checks
// the catalog. Runs automatically before `npm run build` (see "prebuild").
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { CATEGORIES, FEATURED_ORDER, LOCALES, STATUSES, projects } from '../src/data/projects.js'

const SITE = 'https://azizjoon.uz'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

function check() {
  const errors = []
  const seen = new Set()
  for (const p of projects) {
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(p.slug)) errors.push(`${p.slug}: slug must be lowercase a-z, 0-9 and dashes`)
    if (seen.has(p.slug)) errors.push(`${p.slug}: duplicate slug`)
    seen.add(p.slug)
    if (!CATEGORIES.includes(p.category)) errors.push(`${p.slug}: unknown category "${p.category}"`)
    if (!STATUSES.includes(p.status)) errors.push(`${p.slug}: unknown status "${p.status}"`)
    if (p.featured !== FEATURED_ORDER.includes(p.slug)) errors.push(`${p.slug}: "featured" and FEATURED_ORDER disagree`)
    for (const l of LOCALES) {
      if (!p.content[l].title) errors.push(`${p.slug}: missing ${l} title`)
    }
    for (const src of [p.cover, ...p.screenshots.map((s) => s.src)].filter(Boolean)) {
      if (!fs.existsSync(path.join(root, 'public', src))) errors.push(`${p.slug}: file not found public${src}`)
    }
  }
  if (errors.length) {
    console.error(`projects.js has ${errors.length} problem(s):\n  - ${errors.join('\n  - ')}`)
    process.exit(1)
  }
}

function url(loc, priority) {
  return `  <url>\n    <loc>${SITE}${loc}</loc>\n    <priority>${priority}</priority>\n  </url>`
}

check()

const urls = [
  url('/', '1.0'),
  url('/projects', '0.9'),
  ...projects.map((p) => url(`/projects/${p.slug}`, p.featured ? '0.8' : '0.6'))
]

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap.mjs from src/data/projects.js. Do not edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.join('\n')}
</urlset>
`

fs.writeFileSync(path.join(root, 'public/sitemap.xml'), xml)
console.log(`sitemap.xml: ${urls.length} URLs`)
